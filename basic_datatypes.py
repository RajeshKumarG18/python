# Program to demonstrate the basic datatype in python


# 1. Integer (Returns the int value)
a = 10
print(a)


# 2. Float (Returns the Float value., eg: // Output: 3.5)
b = 3.5
print(b)


# Complex Number
c = 1 + 5.1j
print(c)


# Strings
d = "Hello Bot!"
print(d)


# Lists
e =  ["apple", "banana", "orange", 4, 5.0]
print(e)


# Tuple
f = (1, 2, "3", 4, 5.0)
print(f)


# dictionary
g = {'a': 6, 3:'b'}
print(g)


# Boolean (Returns True or False)
h = True
print(h)

i = False
print(i)