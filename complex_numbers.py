"""
Complex numbers are written with a "j" as the imaginary part.
"""


x = 3 + 5j # Complex number with real part 3 and imaginary part 5
y = 5j # Complex number with real part 0 and imaginary part 5
z = -5j # Complex number with real part 0 and imaginary part -5

print(type(x))
print(type(y))
print(type(z))