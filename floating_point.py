"""
Float, or "floating point number" is a number, positive or negative, containing one or more decimals.
"""


x = 1.10 # Positive number with decimals
y = 1.0 # Positive number with decimals
z = -35.59 # Negative number with decimals

print(type(x))
print(type(y))
print(type(z))




"""
Float can also be scientific numbers with an "e" to indicate the power of 10.
"""


x = 35e3
y = 12E4
z = -87.7e100

print(type(x))
print(type(y))
print(type(z))