# Python Basics Dictionary Concepts By Coding:

# Dictionaries are the versitile data structures that uses key value pairs.



# Creating a Simple Dictionary

my_dict = {"Rocket": "A vehicle designed to propel itself by ejecting exhaust gas from one end.",
              "Python": "A high-level programming language for general-purpose programming.",
                "Algorithm": "A step-by-step procedure for solving a problem or accomplishing a task."}


# You can add new key value pairs

my_dict["shocked"] = "A Emoji showing surprise or amazement."


# You can also update a value within a dictionary

my_dict["computer"] = "An electronic device for storing and processing data."


# And finally you can remove item in a dictionary using the 'del' keyword

del my_dict["Rocket"]

print(my_dict["Rocket"])
# You can access values by their keys